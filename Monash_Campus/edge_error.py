"""
edge_error.py
======================================================================
Edge (route-level) error for SUMO map-matching output, using the
Newson & Krumm accuracy metric:

    accuracy = (d+ + d-) / d0

    d0  = length of the correct (ground-truth) route
    d-  = length of correct-route segments the matcher MISSED
          ("erroneously subtracted")
    d+  = length of matched-route segments that AREN'T on the correct
          route ("erroneously added")

WHERE THE GROUND-TRUTH ROUTE COMES FROM
-----------------------------------------
Newson & Krumm's ground truth is a known, ordered sequence of road
edges -- exactly what a SUMO <route edges="..."/> already is. That's
full_campus_v2_rou.xml: the eBike's ground-truth trace (the gt_x/gt_y
columns in the matched CSVs) was generated by simulating THIS route, so
its edge list already IS the correct route that d0/d-/d+ are measured
against.

THE PROBLEM YOU FLAGGED -- AND WHY IT TURNS OUT NOT TO BE ONE
-----------------------------------------------------------------
You mentioned not having GPS coordinates for each ground-truth edge, on
the assumption the metric needs to look at individual points to decide
which edge each one "should" be on. It doesn't, in this formulation:
Newson & Krumm's accuracy is a comparison between two ROUTES (ordered
edge lists), not something done point-by-point. You already have both
routes as edge-ID lists, with no GPS coordinates involved at all:

  - the correct route:  the <route edges="..."/> in the rou.xml
  - the matched route:  the edge_id column your matching pipeline
                         already wrote to every row of the matched CSV,
                         collapsed into the sequence of distinct edges
                         actually traversed (see edges_from_matched_csv)

The only per-edge information the metric needs is each edge's LENGTH,
which comes from the network file (net.xml) via sumolib -- not from any
GPS point, ground-truth or otherwise.

If you still want the ground-truth route's own geometry as lat/lon
(e.g. to plot it against the raw phone trace, or to sanity-check that
the recorded ride really followed this route), set
EXPORT_GROUND_TRUTH_GEOMETRY = True below. export_ground_truth_geometry
builds that CSV by walking each ground-truth edge's shape through the
network's own coordinate conversion -- literally "GPS coordinates for
each edge" -- but it's a bonus and isn't used by the accuracy
calculation itself.

No command-line arguments: edit the CONFIG block below and re-run.
----------------------------------------------------------------------
"""

